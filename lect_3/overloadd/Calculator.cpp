#include "Calculator.h"

int Calculator::sum(int n, int m)
{
    return n + m;
}

int Calculator::sum(float n, int m)
{
    return n + m;
}

int Calculator::sum(int n, int m, int q)
{
    return n + m +q;
}

float Calculator::sum(float f, float t)
{
    return f + t;
}

float Calculator::sum(float f, float t, float a)
{
    return f + t + a;
}
